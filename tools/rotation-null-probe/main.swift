/// E. Planted 30° rotation on the analytic phase-object gradient, sd 0.03,
/// 40×40, 60 seeds → certified count; angle error (mod 180°) distribution.
/// Recorded claim: 60 of 60, 9 over 5°, one at 61°.
/// `plantedDeg` is overridable for the sanity check (default 30).
func experimentE(plantedDeg: Double) -> String {
    let width = 40, height = 40, noiseSd = 0.03, n = 60
    var certified = 0
    var errOver5 = 0
    var maxErr = 0.0
    var angles: [Double] = []
    for i in 0..<n {
        let seed: UInt64 = 0xE000_0000_0000_0000 &+ UInt64(i)
        let field = plantedRotationField(width: width, height: height, angleDeg: plantedDeg, noiseSd: noiseSd, seed: seed)
        guard let r = RotationCalibration.solve(com: field, width: width, height: height) else { continue }
        if r.carriesRotation { certified += 1 }
        let deg = angleDegOf(r)
        angles.append(deg)
        let err = angleErrorModHalfCircle(measuredDeg: deg, plantedDeg: plantedDeg)
        if err > 5 { errOver5 += 1 }
        maxErr = Swift.max(maxErr, err)
    }
    let angleRange = angles.isEmpty ? "n/a" : "[\(fmt(angles.min()!)), \(fmt(angles.max()!))]deg"
    let measured = "\(certified)/\(n) certified; err>5deg: \(errOver5); max err \(fmt(maxErr))deg; angle range \(angleRange)"
    let claim = plantedDeg == 30
        ? "60/60; 9 over 5deg; max 61deg"
        : "n/a — sanity check, planted angle overridden to \(Int(plantedDeg))deg"
    return tableRow("E", n, measured, claim)
}

/// F. The same planted 30° rotation at noise sd 0.00, 0.01, 0.02, 0.03,
/// 0.05, 12 seeds each → refusals. Recorded claim: 0 of 60.
func experimentF() -> String {
    let width = 40, height = 40, planted = 30.0, seedsPerLevel = 12
    let sds = [0.00, 0.01, 0.02, 0.03, 0.05]
    var refused = 0
    var total = 0
    for (sdIdx, sd) in sds.enumerated() {
        for i in 0..<seedsPerLevel {
            let seed: UInt64 = 0xF000_0000_0000_0000 &+ UInt64(sdIdx) &* 1000 &+ UInt64(i)
            let field = plantedRotationField(width: width, height: height, angleDeg: planted, noiseSd: sd, seed: seed)
            guard let r = RotationCalibration.solve(com: field, width: width, height: height) else { continue }
            total += 1
            if !r.carriesRotation { refused += 1 }
        }
    }
    let measured = "\(refused)/\(total) refused (sd 0.00-0.05, 12 seeds/level)"
    return tableRow("F", total, measured, "0/60")
}


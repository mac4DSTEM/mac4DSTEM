import warnings; warnings.filterwarnings("ignore")
import logging; logging.disable(logging.WARNING)
import numpy as np, hyperspy.api as hs, exspy
k = [1.450226, 5.075602]
s2 = exspy.data.EDS_TEM_FePt_nanoparticles(); s2.add_lines()
bw = s2.estimate_background_windows(xray_lines=["Fe_Ka", "Pt_La"], line_width=[5.0, 2.0])
print("bg windows keV:", np.round(bw, 6).tolist())
iw = s2.estimate_integration_windows(xray_lines=["Fe_Ka", "Pt_La"])
print("integration windows keV:", np.round(np.array(iw), 6).tolist())
I = s2.get_lines_intensity(xray_lines=["Fe_Ka", "Pt_La"], background_windows=bw)
print("window intensities:", [float(i.data[0]) for i in I])
qa = s2.quantification(I, method="CL", factors=k)
qw = s2.quantification(I, method="CL", factors=k, composition_units="weight")
print("CL window at%:", [round(float(q.data[0]), 6) for q in qa], "wt%:", [round(float(q.data[0]), 6) for q in qw])
s = exspy.data.EDS_TEM_FePt_nanoparticles(); s.add_elements(["Cu"])
m = s.create_model(True); m.set_signal_range(5.5, 10.0); m.fit()
Im = m.get_lines_intensity(xray_lines=["Fe_Ka", "Pt_La"])
print("model components:", [c.name for c in m])
print("model intensities:", [round(float(i.data[0]), 4) for i in Im])
qm = s.quantification(Im, method="CL", factors=k)
print("CL model at%:", [round(float(q.data[0]), 6) for q in qm])
print("model reduced chi2 (ls):", float(np.asarray(m.red_chisq.data).ravel()[0]) if hasattr(m, "red_chisq") else "n/a")
# Poisson ML variant
s3 = exspy.data.EDS_TEM_FePt_nanoparticles(); s3.add_elements(["Cu"]); s3.change_dtype("float")
m3 = s3.create_model(True); m3.set_signal_range(5.5, 10.0); m3.fit(optimizer="Nelder-Mead", loss_function="ML-poisson")
Im3 = m3.get_lines_intensity(xray_lines=["Fe_Ka", "Pt_La"])
print("ML-poisson (Nelder-Mead) intensities:", [round(float(i.data[0]), 4) for i in Im3])

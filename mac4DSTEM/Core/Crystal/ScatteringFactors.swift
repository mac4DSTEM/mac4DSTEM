    /// Electron scattering factor f_e(Z, g²), g² in Å⁻². Returns 0 for
    /// elements not in the embedded table (caller should validate first).
    static func electronScatteringFactor(z: Int, gSquared: Double) -> Double {
        guard let p = table[z] else { return 0 }
        var fe = 0.0
        for i in 0..<5 {
            let a = p[2 * i], b = p[2 * i + 1]
            let denom = 1 + b * gSquared
            fe += a * (2 + b * gSquared) / (denom * denom)
        }
        return fe
    }
